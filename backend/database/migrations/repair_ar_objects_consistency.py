"""Exact compare-and-set repair for the ``ar_objects`` collection.

This module is the *only* code that mutates ``ar_objects`` documents during the
Phase B migration window. Inference from row order, regex, or URL text is
forbidden: every repair is sourced from the reviewed
``ar_object_consistency_map.json`` file and is generated by deterministic
``build_repairs`` + ``build_filter`` helpers.

The CLI accepts ``--expected-db`` (a database name) and ``--apply``. Without
``--apply`` it prints the planned operations as JSON and exits 0. With
``--apply`` it verifies the active MongoDB database name matches the expected
one, then issues a single ``update_many`` per group of identical operations.
"""

from __future__ import annotations

import json
import os
import sys
from dataclasses import dataclass, field
from pathlib import Path
from typing import Any, Iterable, Mapping


# Sentinel that distinguishes "field absent" from "field set to None".
MISSING: object = object()


@dataclass(frozen=True)
class Repair:
    object_id: Any
    ar_tag: str
    set_values: dict[str, Any] = field(default_factory=dict)
    unset_fields: frozenset[str] = field(default_factory=frozenset)
    old_values: dict[str, Any] = field(default_factory=dict)

    def to_operation(self) -> dict[str, Any]:
        operation: dict[str, Any] = {}
        if self.set_values:
            operation["$set"] = dict(self.set_values)
        if self.unset_fields:
            operation["$unset"] = {field: "" for field in self.unset_fields}
        return operation


def _load_mapping(path: Path) -> dict[str, Any]:
    return json.loads(path.read_text(encoding="utf-8"))


def _catalog_spec(mapping: Mapping[str, Any], ar_tag: str) -> dict[str, Any] | None:
    return mapping.get("catalog", {}).get(ar_tag)


def _legacy_set(mapping: Mapping[str, Any]) -> set[str]:
    return set(mapping.get("legacy", []))


def build_repairs(
    documents: Iterable[Mapping[str, Any]],
    mapping: Mapping[str, Any],
) -> list[Repair]:
    legacy_set = _legacy_set(mapping)
    repairs: list[Repair] = []

    for row in documents:
        ar_tag = str(row.get("ar_tag", ""))
        spec = _catalog_spec(mapping, ar_tag)
        set_values: dict[str, Any] = {}
        unset: list[str] = []
        old_values: dict[str, Any] = {}

        if spec is not None:
            # Catalog row: enforce tracking_mode + pair, drop any nft_base_url.
            current_mode = row.get("tracking_mode", MISSING)
            if current_mode != "catalog":
                old_values["tracking_mode"] = current_mode
                set_values["tracking_mode"] = "catalog"
            if row.get("mind_catalog_id") != spec["mind_catalog_id"]:
                old_values["mind_catalog_id"] = row.get("mind_catalog_id", MISSING)
                set_values["mind_catalog_id"] = spec["mind_catalog_id"]
            if row.get("mind_target_index") != spec["mind_target_index"]:
                old_values["mind_target_index"] = row.get("mind_target_index", MISSING)
                set_values["mind_target_index"] = spec["mind_target_index"]
            if "nft_base_url" in row and row.get("nft_base_url") not in (None, ""):
                old_values["nft_base_url"] = row.get("nft_base_url")
                unset.append("nft_base_url")
        elif ar_tag in legacy_set:
            # Legacy row: ensure tracking_mode + kept nft_base_url, drop catalog pair.
            current_mode = row.get("tracking_mode", MISSING)
            if current_mode != "legacy":
                old_values["tracking_mode"] = current_mode
                set_values["tracking_mode"] = "legacy"
            if "mind_catalog_id" in row and row.get("mind_catalog_id") is not None:
                old_values["mind_catalog_id"] = row.get("mind_catalog_id")
                unset.append("mind_catalog_id")
            if row.get("mind_target_index") is not None:
                old_values["mind_target_index"] = row.get("mind_target_index")
                unset.append("mind_target_index")
        else:
            # Unknown ar_tag in any state: no repair planned.
            continue

        if not set_values and not unset:
            continue

        repairs.append(
            Repair(
                object_id=row.get("_id"),
                ar_tag=ar_tag,
                set_values=set_values,
                unset_fields=frozenset(unset),
                old_values=old_values,
            )
        )

    return repairs


def _old_value_clause(field_name: str, old_value: Any) -> dict[str, Any]:
    if old_value is MISSING:
        return {"$or": [{field_name: {"$exists": False}}, {field_name: None}]}
    return {"$or": [{field_name: old_value}, {field_name: {"$eq": old_value}}]}


def build_filter(repair: Repair) -> dict[str, Any]:
    clauses = [
        {"_id": repair.object_id},
        {"ar_tag": repair.ar_tag},
        _old_value_clause(
            "tracking_mode",
            repair.old_values.get("tracking_mode", MISSING),
        ),
        _old_value_clause(
            "mind_catalog_id",
            repair.old_values.get("mind_catalog_id", MISSING),
        ),
        _old_value_clause(
            "mind_target_index",
            repair.old_values.get("mind_target_index", MISSING),
        ),
    ]
    if "nft_base_url" in repair.old_values:
        clauses.append(
            _old_value_clause("nft_base_url", repair.old_values["nft_base_url"])
        )
    return {"$and": clauses}


def _print_plan(repairs: list[Repair]) -> None:
    plan = [
        {
            "ar_tag": repair.ar_tag,
            "object_id": repair.object_id,
            "operation": repair.to_operation(),
            "filter": build_filter(repair),
        }
        for repair in repairs
    ]
    sys.stdout.write(json.dumps(plan, default=str, indent=2, sort_keys=True))
    sys.stdout.write("\n")


def _resolve_mapping_path(arg: str | None) -> Path:
    if arg:
        return Path(arg)
    return Path(__file__).with_name("ar_object_consistency_map.json")


async def _apply_repairs_async(
    repairs: list[Repair],
    collection,
) -> dict[str, int]:
    """Issue ``update_one`` per repair and return counts.

    Requires ``matched_count == 1`` for every filter — if a document changed
    between dry-run and apply, we stop immediately and return non-zero so the
    operator can re-run dry-run.
    """
    applied = 0
    failed = 0
    for repair in repairs:
        filter_doc = build_filter(repair)
        result = await collection.update_one(filter_doc, repair.to_operation())
        if result.matched_count == 1:
            applied += 1
            sys.stderr.write(
                f"[repair] updated ar_tag={repair.ar_tag} "
                f"matched=1 modified={result.modified_count}\n"
            )
        else:
            failed += 1
            sys.stderr.write(
                f"[repair] FAILED ar_tag={repair.ar_tag} "
                f"matched={result.matched_count} (expected 1 — document changed since dry-run?)\n"
            )
            # Stop on first failure so the operator re-runs dry-run.
            break
    return {"applied": applied, "failed": failed}


def main(argv: list[str] | None = None) -> int:
    import argparse
    import asyncio

    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--mapping", default=None, help="Path to consistency map JSON")
    parser.add_argument("--apply", action="store_true", help="Apply repairs to MongoDB")
    parser.add_argument(
        "--expected-db",
        default=os.environ.get("MONGO_DB"),
        help="Active database must match this name when --apply is set",
    )
    args = parser.parse_args(argv)

    mapping_path = _resolve_mapping_path(args.mapping)
    mapping = _load_mapping(mapping_path)

    if not args.apply:
        # Dry-run: documents come from stdin as JSON.
        raw = sys.stdin.read()
        try:
            documents = json.loads(raw) if raw.strip() else []
        except json.JSONDecodeError as exc:
            sys.stderr.write(f"error: stdin is not valid JSON: {exc}\n")
            return 1
        repairs = build_repairs(documents, mapping)
        sys.stderr.write(f"[repair] dry-run: {len(repairs)} repair(s) planned\n")
        _print_plan(repairs)
        return 0

    # Apply path — requires live MongoDB connection.
    if not args.expected_db:
        sys.stderr.write("error: --expected-db is required with --apply\n")
        return 2

    env_db = os.environ.get("MONGO_DB", "")
    if env_db != args.expected_db:
        sys.stderr.write(
            f"error: active database {env_db!r} != expected {args.expected_db!r}\n"
            "error: refusing to apply to the wrong database\n"
        )
        return 2

    # Open real Motor connection.
    mongo_url = os.environ.get("MONGO_URL")
    if not mongo_url:
        sys.stderr.write("error: MONGO_URL environment variable is not set\n")
        return 2

    try:
        import motor.motor_asyncio
        import certifi
    except ImportError as exc:
        sys.stderr.write(f"error: pymongo/motor is not installed: {exc}\n")
        return 1

    sys.stderr.write(
        f"[repair] connecting to {mongo_url} / {args.expected_db}\n"
    )
    client = motor.motor_asyncio.AsyncIOMotorClient(
        mongo_url,
        tls=True,
        tlsCAFile=certifi.where(),
        serverSelectionTimeoutMS=5000,
    )

    async def _run():
        db = client[args.expected_db]
        coll = db["ar_objects"]

        # 1. Read all documents.
        docs = await coll.find().to_list(length=None)
        sys.stderr.write(f"[repair] read {len(docs)} document(s) from ar_objects\n")

        # 2. Build repairs from current state.
        repairs = build_repairs(docs, mapping)
        if not repairs:
            sys.stderr.write("[repair] no repairs needed — collection is consistent\n")
            return 0

        sys.stderr.write(f"[repair] applying {len(repairs)} repair(s)\n")

        # 3. Apply each repair with compare-and-set.
        result = await _apply_repairs_async(repairs, coll)

        # 4. Re-read to confirm.
        docs_after = await coll.find().to_list(length=None)
        repaired_tags = {r.ar_tag for r in repairs}
        remaining = [
            d for d in build_repairs(docs_after, mapping)
            if d.ar_tag in repaired_tags
        ]
        if remaining:
            sys.stderr.write(
                f"[repair] WARNING: {len(remaining)} repair(s) still appear after apply — "
                "re-run dry-run and investigate\n"
            )
            return 1

        sys.stderr.write(
            f"[repair] SUCCESS: {result['applied']} updated, {result['failed']} failed\n"
        )
        return 1 if result["failed"] else 0

    try:
        exit_code = asyncio.run(_run())
    except Exception as exc:
        sys.stderr.write(f"[repair] FATAL: {exc}\n")
        exit_code = 1
    finally:
        client.close()
    return exit_code


if __name__ == "__main__":
    raise SystemExit(main())


__all__ = ["MISSING", "Repair", "build_filter", "build_repairs", "main"]